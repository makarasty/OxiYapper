    /// Positive-going zero crossings per second: the pitch of a sine.
    fn pitch(samples: &[f32], rate: u32) -> f32 {
        let up = samples
            .windows(2)
            .filter(|w| w[0] < 0.0 && w[1] >= 0.0)
            .count();
        up as f32 * rate as f32 / samples.len() as f32
    }

    /// Decodes `bytes` at `rate`; the tone is there at 440 Hz and the length is 0.1 s or a few
    /// codec frames more.
    fn tone(name: &str, bytes: &[u8], rate: u32) {
        let file = Temp::new(name, bytes);
        let got = decode_file(&file.0, rate).unwrap_or_else(|e| panic!("{name}: {e}"));
        // Codecs pad the ends to whole frames: 0.1 s, never fewer.
        let len = got.len();
        let tenth = rate as usize / 10;
        assert!((tenth..=tenth * 4).contains(&len), "{name}: {len}");
        assert!(got.iter().any(|s| s.abs() > 0.05), "{name}: silence");
        // The padding is silence, so the pitch is judged over the loud middle only.
        let first = got.iter().position(|s| s.abs() > 0.03).unwrap();
        let last = got.iter().rposition(|s| s.abs() > 0.03).unwrap();
        let hz = pitch(&got[first..=last], rate);
        assert!((hz - 440.0).abs() < 60.0, "{name}: {hz} Hz");
    }

