/// The longest audio taken, in minutes (the cap `audio.max_seconds` allows).
pub const MAX_MINUTES: u64 = 120;

/// What the drop zone and the file dialog list.
pub const EXTENSIONS: [&str; 6] = ["wav", "mp3", "m4a", "mp4", "flac", "ogg"];

/// Seconds of the file's own audio gathered before one resample.
/// shortcut: each block is resampled on its own, so its edges get a few ms of filter ramp every
/// 30 s; harmless for speech, upgrade to the stream resampler of `oxi_core::audio` once it is public.
const BLOCK_SECONDS: usize = 30;

/// Samples taken from a wav reader at a time.
const READ: usize = 4096;

/// The file rates taken: a rate outside would ask the resampler for absurd sizes (a 1 Hz wav grows
/// 16000x), as `oxi_core::sounds` limits custom sounds.
const RATES: RangeInclusive<u32> = 4_000..=384_000;

#[derive(Debug, Error)]
pub enum DecodeError {
    /// A format or codec this build cannot read; `what` names it.
    #[error("{what} cannot be read here")]
    Unsupported { what: String },
    #[error("the file is damaged or holds no audio")]
    Corrupt,
    #[error("the audio is longer than {MAX_MINUTES} minutes")]
    TooLong,
    #[error("the file cannot be opened")]
    Io(#[from] io::Error),
    /// The decoding child was stopped (Stop, window closed); only [`decode_in_child`] gives it.
    #[error("stopped")]
    Stopped,
}

fn unsupported(what: &str) -> DecodeError {
    DecodeError::Unsupported { what: what.into() }
}

/// Decodes the audio file at `path` to mono samples in `[-1, 1]` at `rate` Hz.
///
/// # Errors
/// [`DecodeError`]: an unknown or unsupported format (Opus, ALAC, anything else), a file that is
/// damaged or has no audio, more than [`MAX_MINUTES`] of audio, or a file that cannot be opened.
pub fn decode_file(path: &Path, rate: u32) -> Result<Vec<f32>, DecodeError> {
    let ext = path
        .extension()
        .and_then(|e| e.to_str())
        .map(str::to_ascii_lowercase)
        .unwrap_or_default();
    let file = File::open(path)?;
    match ext.as_str() {
        "wav" => decode_wav(file, rate),
        "ogg" => decode_ogg(file, rate),
        "opus" => Err(unsupported("Opus")),
        _ => decode_stream(file, &ext, rate),
    }
}

fn check_length(frames: u64, rate: u32) -> Result<(), DecodeError> {
    if frames > MAX_MINUTES * 60 * u64::from(rate) {
        return Err(DecodeError::TooLong);
    }
    Ok(())
}

/// Mono audio on its way from the file's rate to the asked one, a block at a time.
struct Sink {
    from: u32,
    to: u32,
    block: usize,
    /// Frames of the file's own rate taken so far.
    frames: u64,
    pending: Vec<f32>,
    out: Vec<f32>,
}

impl Sink {
    /// `frames`: the length the file's header tells, if it does; over the cap is refused here,
    /// before anything is decoded.
    fn new(from: u32, to: u32, frames: Option<u64>) -> Result<Self, DecodeError> {
        if from == 0 || to == 0 {
            return Err(DecodeError::Corrupt);
        }
        if !RATES.contains(&from) {
            return Err(unsupported(&format!("{from} Hz audio")));
        }
        if let Some(frames) = frames {
            check_length(frames, from)?;
        }
        let mut sink = Self::with_block(from, to, from as usize * BLOCK_SECONDS);
        // The told length (at most the cap's worth), so the output never grows by doubling.
        let out = frames.map_or(0, |n| n * u64::from(to) / u64::from(from));
        sink.out.reserve_exact(usize::try_from(out).unwrap_or(0));
        Ok(sink)
    }

    fn with_block(from: u32, to: u32, block: usize) -> Self {
        Self {
            from,
            to,
            block: block.max(1),
            frames: 0,
            pending: Vec::new(),
            out: Vec::new(),
        }
    }

    /// Adds interleaved frames of `channels` samples, averaged to mono; a partial frame is dropped.
    fn push(&mut self, interleaved: &[f32], channels: usize) -> Result<(), DecodeError> {
        let channels = channels.max(1);
        for frame in interleaved.chunks_exact(channels) {
            self.pending
                .push(frame.iter().sum::<f32>() / channels as f32);
            if self.pending.len() >= self.block {
                self.flush()?;
            }
        }
        Ok(())
    }

    fn flush(&mut self) -> Result<(), DecodeError> {
        self.frames += self.pending.len() as u64;
        check_length(self.frames, self.from)?;
        if self.from == self.to {
            self.out.append(&mut self.pending);
        } else {
            let piece =
                resample(&self.pending, self.from, self.to).map_err(|_| DecodeError::Corrupt)?;
            self.out.extend_from_slice(&piece);
            self.pending.clear();
        }
        Ok(())
    }

    fn finish(mut self) -> Result<Vec<f32>, DecodeError> {
        self.flush()?;
        if self.out.is_empty() {
            return Err(DecodeError::Corrupt);
        }
        Ok(self.out)
    }
}

/// A streamed wav (`ffmpeg -f wav -`, `arecord` to stdout) tells a placeholder data size,
/// 0xFFFFFFFF, which hound refuses as corrupt before any frame is read (hound 3.5.1 read.rs:608).
/// Returns where the data chunk's size field is and the size that fits the bytes really there,
/// rounded down to a whole frame; `None` when the told size already fits or the header is not
/// one this can read (hound then judges the file as it is).
fn data_size_fix(file: &mut File, len: u64) -> Option<(u64, u32)> {
    let mut head = [0_u8; 12];
    file.read_exact(&mut head).ok()?;
    if &head[..4] != b"RIFF" || &head[8..] != b"WAVE" {
        return None;
    }
    let (mut pos, mut block) = (12_u64, 0_u64);
    // A real header has a handful of chunks; a file of thousands of tiny ones is judged by hound.
    for _ in 0..64 {
        file.seek(io::SeekFrom::Start(pos)).ok()?;
        let mut chunk = [0_u8; 8];
        file.read_exact(&mut chunk).ok()?;
        let size = u64::from(u32::from_le_bytes(chunk[4..].try_into().ok()?));
        match &chunk[..4] {
            b"fmt " if size >= 16 => {
                let mut fmt = [0_u8; 16];
                file.read_exact(&mut fmt).ok()?;
                block = u64::from(u16::from_le_bytes([fmt[12], fmt[13]]));
            }
            b"data" => {
                let remaining = len.checked_sub(pos + 8)?;
                if block == 0 || (size <= remaining && size % block == 0) {
                    return None;
                }
                return Some((pos + 4, u32::try_from(remaining - remaining % block).ok()?));
            }
            _ => {}
        }
        pos += 8 + size + (size & 1);
    }
    None
}

/// `inner` with four bytes replaced at an offset: the corrected data size of [`data_size_fix`].
struct Patch<R> {
    inner: R,
    at: u64,
    bytes: [u8; 4],
    pos: u64,
}

impl<R> Patch<R> {
    fn new(inner: R, fix: Option<(u64, u32)>) -> Self {
        let (at, size) = fix.unwrap_or((u64::MAX - 4, 0));
        Self {
            inner,
            at,
            bytes: size.to_le_bytes(),
            pos: 0,
        }
    }
}

impl<R: Read> Read for Patch<R> {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        let n = self.inner.read(buf)?;
        for (i, byte) in buf[..n].iter_mut().enumerate() {
            let offset = self.pos + i as u64;
            if let Some(&patched) = offset
                .checked_sub(self.at)
                .and_then(|d| usize::try_from(d).ok())
                .and_then(|d| self.bytes.get(d))
            {
                *byte = patched;
            }
        }
        self.pos += n as u64;
        Ok(n)
    }
}

fn decode_wav(file: File, rate: u32) -> Result<Vec<f32>, DecodeError> {
    let mut file = file;
    let bytes = file.metadata()?.len();
    let fix = data_size_fix(&mut file, bytes);
    file.rewind()?;
    let source = Patch::new(file, fix);
    let mut reader = WavReader::new(BufReader::new(source)).map_err(|_| DecodeError::Corrupt)?;
    let spec = reader.spec();
    let channels = usize::from(spec.channels);
    if channels == 0 {
        return Err(DecodeError::Corrupt);
    }
    // A streamed wav (`ffmpeg -f wav -`) tells 0xFFFFFFFF bytes of data: the file's size caps the
    // told frames, so only a file that really holds over the cap is refused here.
    let frame_bytes = u64::from(spec.channels) * u64::from(spec.bits_per_sample.div_ceil(8));
    let told = u64::from(reader.duration()).min(bytes / frame_bytes.max(1));
    let mut sink = Sink::new(spec.sample_rate, rate, Some(told))?;
    match (spec.sample_format, spec.bits_per_sample) {
        (SampleFormat::Float, 32) => feed(&mut sink, reader.samples::<f32>(), |s| s, channels)?,
        (SampleFormat::Int, bits @ 8..=32) => {
            let scale = 2.0_f32.powi(i32::from(bits) - 1);
            feed(
                &mut sink,
                reader.samples::<i32>(),
                |s| s as f32 / scale,
                channels,
            )?;
        }
        (format, bits) => return Err(unsupported(&format!("{format:?} {bits} bit WAV"))),
    }
    sink.finish()
}

/// Reads `samples` into `sink` a few thousand at a time. A read error ends the audio: a file cut
/// short keeps what was read.
fn feed<S>(
    sink: &mut Sink,
    samples: impl Iterator<Item = Result<S, hound::Error>>,
    to_f32: impl Fn(S) -> f32,
    channels: usize,
) -> Result<(), DecodeError> {
    let mut buf = Vec::with_capacity(READ * channels);
    for sample in samples {
        let Ok(sample) = sample else { break };
        buf.push(to_f32(sample));
        if buf.len() >= READ * channels {
            sink.push(&buf, channels)?;
            buf.clear();
        }
    }
    sink.push(&buf, channels)
}

fn decode_ogg(mut file: File, rate: u32) -> Result<Vec<f32>, DecodeError> {
    check_vorbis(&mut file)?;
    file.rewind()?;
    let mut reader =
        OggStreamReader::new(BufReader::new(file)).map_err(|_| DecodeError::Corrupt)?;
    let channels = usize::from(reader.ident_hdr.audio_channels);
    let mut sink = Sink::new(reader.ident_hdr.audio_sample_rate, rate, None)?;
    // A damaged packet ends the audio: a file cut short keeps what was read.
    while let Ok(Some(packet)) = reader.read_dec_packet_itl() {
        let samples: Vec<f32> = packet.iter().map(|&s| f32::from(s) / 32_768.0).collect();
        sink.push(&samples, channels)?;
    }
    sink.finish()
}

/// lewton sizes its buffers from the header counts before it reads them (a 300-byte file asked
/// for 55 GB): the three headers first pass the check of `oxi_core::sounds::decode_ogg`, given
/// the bytes of the file up to the end of the setup header. Opus in Ogg is named.
fn check_vorbis(file: &mut File) -> Result<(), DecodeError> {
    let mut packets = ogg::PacketReader::new(BufReader::new(&mut *file));
    let mut next = || {
        packets
            .read_packet()
            .ok()
            .flatten()
            .ok_or(DecodeError::Corrupt)
    };
    let first = next()?;
    if first.data.starts_with(b"OpusHead") {
        return Err(unsupported("Opus"));
    }
    if !first.data.starts_with(b"\x01vorbis") {
        return Err(unsupported("this audio codec"));
    }
    let serial = first.stream_serial();
    let mut headers = 1;
    while headers < 3 {
        if next()?.stream_serial() == serial {
            headers += 1;
        }
    }
    let end = packets.into_inner().stream_position()?;
    let mut head = Vec::new();
    file.rewind()?;
    file.take(end).read_to_end(&mut head)?;
    match oxi_core::sounds::decode_ogg(&head) {
        // The bytes end after the headers: no audio, or a first page of it.
        Ok(_) | Err(oxi_core::sounds::WavError::Empty | oxi_core::sounds::WavError::TooLong) => {
            Ok(())
        }
        Err(_) => Err(DecodeError::Corrupt),
    }
}

/// The symphonia path; `ext` (lower case) is only a hint for the probe.
fn decode_stream(file: File, ext: &str, rate: u32) -> Result<Vec<f32>, DecodeError> {
    let mut hint = Hint::new();
    hint.with_extension(ext);
    let stream = MediaSourceStream::new(Box::new(file), MediaSourceStreamOptions::default());
    let probed = symphonia::default::get_probe()
        .format(
            &hint,
            stream,
            &FormatOptions::default(),
            &MetadataOptions::default(),
        )
        .map_err(|e| match e {
            SymError::Unsupported(_) => unsupported(if ext.is_empty() { "this file" } else { ext }),
            _ => DecodeError::Corrupt,
        })?;
    let mut format = probed.format;
    let (id, params) = format
        .tracks()
        .iter()
        .find(|t| t.codec_params.codec != CODEC_TYPE_NULL)
        .map(|t| (t.id, t.codec_params.clone()))
        .ok_or_else(|| unsupported("this audio"))?;
    let mut decoder = symphonia::default::get_codecs()
        .make(&params, &DecoderOptions::default())
        .map_err(|_| {
            unsupported(match params.codec {
                CODEC_TYPE_OPUS => "Opus",
                CODEC_TYPE_ALAC => "ALAC",
                _ => "this audio codec",
            })
        })?;
    // The container's length, when it tells one, refuses a long file before decoding it.
    if let (Some(from), Some(frames)) = (params.sample_rate, params.n_frames) {
        check_length(frames, from)?;
    }
    let mut sink: Option<Sink> = None;
    let mut buffer: Option<SampleBuffer<f32>> = None;
    loop {
        let packet = match format.next_packet() {
            Ok(packet) => packet,
            // The end of the stream, and a file cut short: what was read stays.
            Err(SymError::IoError(_) | SymError::ResetRequired) => break,
            Err(_) => return Err(DecodeError::Corrupt),
        };
        if packet.track_id() != id {
            continue;
        }
        match decoder.decode(&packet) {
            Ok(block) => {
                let spec = *block.spec();
                if sink.is_none() {
                    // The told length is in the decoder's frames only when the rates agree.
                    let told = params
                        .n_frames
                        .filter(|_| params.sample_rate == Some(spec.rate));
                    sink = Some(Sink::new(spec.rate, rate, told)?);
                }
                let buf =
                    buffer.get_or_insert_with(|| SampleBuffer::new(block.capacity() as u64, spec));
                buf.copy_interleaved_ref(block);
                if let Some(sink) = &mut sink {
                    sink.push(buf.samples(), spec.channels.count())?;
                }
            }
            // One bad frame is skipped, as players do.
            Err(SymError::DecodeError(_)) => {}
            Err(_) => break,
        }
    }
    sink.ok_or(DecodeError::Corrupt)?.finish()
}

/// The hidden first argument that makes the exe a decoding child: `<exe> --decode-child <path>`.
pub const CHILD_ARG: &str = "--decode-child";

/// How often the wait for a child looks at the stop flag (as the daemon's file run does).
const POLL: Duration = Duration::from_millis(50);

/// Reply tags: the first byte the child writes.
const OK: u8 = 0;
const UNSUPPORTED: u8 = 1;
const CORRUPT: u8 = 2;
const TOO_LONG: u8 = 3;
const IO: u8 = 4;

/// The child's whole life: decodes `path` at `rate` and writes the reply to stdout. Returns the
/// process exit code.
#[must_use]
pub fn child_main(path: &Path, rate: u32) -> i32 {
    i32::from(write_reply(io::stdout().lock(), &decode_file(path, rate)).is_err())
}

/// Decodes `path` at `rate` in a child process of this exe, whose `main` hands [`CHILD_ARG`] to
/// [`child_main`]: a panic, an abort or any other bad end of the child is
/// [`DecodeError::Corrupt`]. `stop` set: the child is killed and `Stopped` comes back.
///
/// # Errors
/// As [`decode_file`], plus `Stopped`; a child that cannot be started is `Io`.
pub fn decode_in_child(path: &Path, rate: u32, stop: &AtomicBool) -> Result<Vec<f32>, DecodeError> {
    let mut command = Command::new(std::env::current_exe()?);
    command
        .arg(CHILD_ARG)
        .arg(path)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::null());
    #[cfg(windows)]
    {
        use std::os::windows::process::CommandExt;
        /// No console window for a child of the console-subsystem debug build.
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        command.creation_flags(CREATE_NO_WINDOW);
    }
    let mut child = command.spawn()?;
    #[cfg(windows)]
    job::guard(&child);
    let Some(out) = child.stdout.take() else {
        end(&mut child);
        return Err(DecodeError::Corrupt);
    };
    wait(child, out, rate, stop)
}

/// Reads the reply of `child` from `out` on a thread of its own and waits for it, killing the
/// child when `stop` is set. The reply counts only from a child that exited well.
fn wait(
    mut child: Child,
    out: impl Read + Send + 'static,
    rate: u32,
    stop: &AtomicBool,
) -> Result<Vec<f32>, DecodeError> {
    let (tx, rx) = mpsc::channel();
    let reader = thread::Builder::new()
        .name("file-decode".into())
        .spawn(move || {
            let _ = tx.send(read_reply(out, rate));
        });
    if reader.is_err() {
        end(&mut child);
        return Err(DecodeError::Corrupt);
    }
    loop {
        if stop.load(Ordering::Acquire) || QUIT.load(Ordering::Acquire) {
            end(&mut child);
            return Err(DecodeError::Stopped);
        }
        match rx.recv_timeout(POLL) {
            // The reader saw the pipe close: the child has ended or is ending.
            Ok(reply) => {
                return match child.wait() {
                    Ok(status) if status.success() => reply,
                    _ => Err(DecodeError::Corrupt),
                };
            }
            Err(RecvTimeoutError::Timeout) => {}
            Err(RecvTimeoutError::Disconnected) => {
                end(&mut child);
                return Err(DecodeError::Corrupt);
            }
        }
    }
}

/// Set by the daemon's orderly quit: every decode in hand kills its child and ends as `Stopped`.
static QUIT: AtomicBool = AtomicBool::new(false);

/// Ends every decoding child of this process within [`POLL`] (tray Quit, IPC Shutdown, session
/// end). Any other end of the process kills them too, through the job they sit in.
pub fn stop_all() {
    QUIT.store(true, Ordering::Release);
}

/// The kill-on-close Job object every decoding child joins, so no child outlives the daemon (a
/// decode left running would hold memory and lock the exe against an update).
#[cfg(windows)]
mod job {
    use std::io;
    use std::os::windows::io::{AsRawHandle, FromRawHandle, OwnedHandle};
    use std::process::Child;
    use std::sync::OnceLock;

    use windows_sys::Win32::System::JobObjects::{
        AssignProcessToJobObject, CreateJobObjectW, JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE,
        JOBOBJECT_EXTENDED_LIMIT_INFORMATION, JobObjectExtendedLimitInformation,
        SetInformationJobObject,
    };

    /// Made at the first decode and never closed: the kernel closes it when the process ends,
    /// however it ends (Quit, session end, a crash), and that kills every child in it.
    static JOB: OnceLock<Option<OwnedHandle>> = OnceLock::new();

    /// Puts `child` in the process's job. A job that cannot be made or joined leaves the child
    /// unguarded: the decode still runs, and Stop still kills it.
    pub(super) fn guard(child: &Child) {
        let job = JOB.get_or_init(|| {
            kill_on_close()
                .inspect_err(|e| tracing::warn!("decode job not made: {e}"))
                .ok()
        });
        if let Some(job) = job
            && let Err(e) = assign(job, child)
        {
            tracing::warn!("decoding child not put in the job: {e}");
        }
    }

    /// A new Job object that kills its processes when its last handle closes.
    pub(super) fn kill_on_close() -> io::Result<OwnedHandle> {
        // SAFETY: no attributes, no name; a null return is the error.
        let raw = unsafe { CreateJobObjectW(std::ptr::null(), std::ptr::null()) };
        if raw.is_null() {
            return Err(io::Error::last_os_error());
        }
        // SAFETY: `raw` is a fresh handle that nothing else owns.
        let job = unsafe { OwnedHandle::from_raw_handle(raw) };
        let mut info = JOBOBJECT_EXTENDED_LIMIT_INFORMATION::default();
        info.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
        // SAFETY: `info` is the struct the class names and outlives the call; the size is its own.
        let ok = unsafe {
            SetInformationJobObject(
                job.as_raw_handle(),
                JobObjectExtendedLimitInformation,
                (&raw const info).cast(),
                u32::try_from(size_of_val(&info)).unwrap_or(u32::MAX),
            )
        };
        if ok == 0 {
            return Err(io::Error::last_os_error());
        }
        Ok(job)
    }

    pub(super) fn assign(job: &OwnedHandle, child: &Child) -> io::Result<()> {
        // SAFETY: both handles are live for the call.
        if unsafe { AssignProcessToJobObject(job.as_raw_handle(), child.as_raw_handle()) } == 0 {
            return Err(io::Error::last_os_error());
        }
        Ok(())
    }
}

fn end(child: &mut Child) {
    let _ = child.kill();
    let _ = child.wait();
}

fn write_reply(out: impl Write, reply: &Result<Vec<f32>, DecodeError>) -> io::Result<()> {
    let mut out = io::BufWriter::new(out);
    match reply {
        Ok(samples) => {
            out.write_all(&[OK])?;
            out.write_all(&(samples.len() as u64).to_le_bytes())?;
            for sample in samples {
                out.write_all(&sample.to_le_bytes())?;
            }
        }
        Err(DecodeError::Unsupported { what }) => {
            out.write_all(&[UNSUPPORTED])?;
            out.write_all(what.as_bytes())?;
        }
        Err(DecodeError::TooLong) => out.write_all(&[TOO_LONG])?,
        Err(DecodeError::Io(_)) => out.write_all(&[IO])?,
        Err(DecodeError::Corrupt | DecodeError::Stopped) => out.write_all(&[CORRUPT])?,
    }
    out.flush()
}

/// The child's reply; anything this exe would not write is `Corrupt`. The sample count is checked
/// against the cap before anything is reserved, so a wrong child cannot make the daemon allocate.
fn read_reply(mut out: impl Read, rate: u32) -> Result<Vec<f32>, DecodeError> {
    let mut tag = [0_u8];
    out.read_exact(&mut tag).map_err(|_| DecodeError::Corrupt)?;
    let reply = match tag[0] {
        OK => read_samples(&mut out, rate),
        UNSUPPORTED => {
            let mut what = String::new();
            (&mut out)
                .take(256)
                .read_to_string(&mut what)
                .map_err(|_| DecodeError::Corrupt)?;
            Err(DecodeError::Unsupported { what })
        }
        TOO_LONG => Err(DecodeError::TooLong),
        IO => Err(DecodeError::Io(io::Error::other(
            "not opened by the decoding child",
        ))),
        _ => Err(DecodeError::Corrupt),
    };
    // To the end: the pipe closes when the child ends, and nothing may follow the reply.
    match out.read(&mut [0]) {
        Ok(0) => reply,
        _ => Err(DecodeError::Corrupt),
    }
}

fn read_samples(out: &mut impl Read, rate: u32) -> Result<Vec<f32>, DecodeError> {
    let mut len = [0_u8; 8];
    out.read_exact(&mut len).map_err(|_| DecodeError::Corrupt)?;
    // The cap and a second of codec padding.
    let cap = (MAX_MINUTES * 60 + 1) * u64::from(rate);
    let len = u64::from_le_bytes(len);
    if len > cap {
        return Err(DecodeError::TooLong);
    }
    let len = usize::try_from(len).map_err(|_| DecodeError::TooLong)?;
    let mut samples = Vec::with_capacity(len);
    let mut buf = vec![0_u8; 64 * 1024];
    while samples.len() < len {
        let want = ((len - samples.len()) * 4).min(buf.len());
        out.read_exact(&mut buf[..want])
            .map_err(|_| DecodeError::Corrupt)?;
        samples.extend(
            buf[..want]
                .as_chunks::<4>()
                .0
                .iter()
                .map(|&b| f32::from_le_bytes(b)),
        );
    }
    Ok(samples)
}

